"""Feasibility repair for long-only portfolio optimization.

Portfolio 2026, Problem 2, page 10 requires every candidate
solution to be repaired before objective evaluation.

The repair consists of two steps:

1. Euclidean simplex projection:
   Ensure non-negative weights that sum to one.

2. Minimum-return repair:
   Ensure that the expected portfolio return meets the
   required target.

The same repair procedure is used by all three ES variants.
"""
import math

from evolution_strategy.portfolio import Portfolio
from evolution_strategy.evaluation import evaluate_profit


def project_simplex(weights: list[float]) -> list[float]:
    """Project candidate weights onto the probability simplex.

    A candidate generated by Gaussian mutation may contain
    negative weights or weights that do not sum to one.

    The assignment requires Euclidean simplex projection:

        q_i = max(z_i - theta, 0)

    where:
        z_i   = original candidate weight
        q_i   = projected weight
        theta = threshold chosen so that sum(q_i) = 1

    This finds the closest feasible weight vector in
    Euclidean distance.

    The sorting-based implementation has O(n log n)
    computational complexity.
    """
    # An empty vector cannot represent a portfolio.
    if not weights:
        raise ValueError("Cannot project an empty weight vector")
    # Reject NaN and infinite values before projection.
    if not all(math.isfinite(value) for value in weights):
        raise ValueError("All portfolio weights must be finite")

    # Sort weights from largest to smallest to identify
    # which coordinates remain positive after projection.
    ordered = sorted(weights, reverse=True)
    running_sum = 0.0
    theta = 0.0

    for rank, value in enumerate(ordered, start=1):
        # Sum the largest candidate weights encountered.
        running_sum += value

        # Calculate the threshold assuming that the first
        # 'rank' weights remain positive after projection.
        candidate_theta = (running_sum - 1.0) / rank

        # Retain the threshold when the current coordinate
        # remains positive after subtracting it.
        if value > candidate_theta:
            theta = candidate_theta

    # Apply the threshold to the original vector.
    # Preserve asset order and set negative values to zero.
    return [max(value - theta, 0.0) for value in weights]


def repair(portfolio: list[Portfolio], weights: list[float], target_return: float) -> list[float]:
    """Repair candidate weights before objective evaluation.

    Required portfolio constraints:

        w_i >= 0
        sum(w_i) = 1
        R(w) >= target_return

    Simplex projection satisfies the first two constraints.
    Return-target repair satisfies the third constraint
    while preserving the first two.
    """
    n = len(portfolio)

    # STEP 1: Budget and non-negativity repair. Required Euclidean simplex projection (not clipping + normalization)
    weights = project_simplex(weights)

    # STEP 2: Minimum expected-return repair.
    # Calculate the expected return after simplex projection.
    # If profit is below target_return, shift weight toward best-profit company
    current_profit = evaluate_profit(portfolio, weights)

    # No additional repair is required when the projected
    # portfolio already meets the minimum return target.
    if current_profit >= target_return:
        return weights

    # Find the asset with the highest expected return.
    # This corresponds to index j and r_max in the PDF.
    best_idx = max(range(n), key=lambda i: portfolio[i].profit)
    max_profit = portfolio[best_idx].profit

    # Defensive check: avoid division by zero when mixing
    # toward the highest-return asset cannot improve return.
    if max_profit <= current_profit:
        return weights

    # Calculate the mixing coefficient beta:
    #
    # beta = (R_min - R(q)) / (r_max - R(q))
    #
    # Beta determines how much portfolio weight must be
    # transferred toward the highest-return asset.
    beta = min(1.0, (target_return - current_profit) / (max_profit - current_profit))

    #Construct the convex combination:
    #
    # w = (1 - beta) * q + beta * e_j
    #
    # e_j represents a portfolio investing entirely in
    # the highest-return asset.
    weights = [(1.0 - beta) * w for w in weights]

    # Allocate the remaining beta fraction to asset j.
    weights[best_idx] += beta

    # Return the repaired portfolio for objective evaluation.
    return weights
